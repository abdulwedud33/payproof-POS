import re
from typing import Dict, Any
from app.schemas import ProviderEvidence, ProviderKind, ProviderPaymentStatus, SafeFetchErrorCode
from app.safe_fetch import SafeFetchException


def parse_mock_receipt_html(
    html: str,
    provider: ProviderKind,
    host: str,
    path: str,
    raw_hash: str,
    http_status: int,
    duration_ms: float,
) -> ProviderEvidence:
    """
    Parses synthetic mock receipt pages generated by services/mock-provider.
    Fails safely without guessing if mandatory fields are missing.
    """
    # Regex extractors for mock HTML structure
    amount_match = re.search(r'id="receipt-amount">([^<]+)<', html)
    txnid_match = re.search(r'id="receipt-txnid">([^<]+)<', html)
    date_match = re.search(r'id="receipt-date">([^<]+)<', html)
    status_match = re.search(r'id="status-badge">([^<]+)<', html)
    receiver_name_match = re.search(r'id="receipt-receiver-name">([^<]+)<', html)
    receiver_acc_match = re.search(r'id="receipt-receiver-account">([^<]+)<', html)
    payer_name_match = re.search(r'id="receipt-payer-name">([^<]+)<', html)

    if not amount_match or not txnid_match or not status_match:
        raise SafeFetchException(
            SafeFetchErrorCode.MALFORMED_PAGE,
            "Mock provider page missing mandatory fields (amount, transaction ID, or status)",
            {"has_amount": bool(amount_match), "has_txnid": bool(txnid_match), "has_status": bool(status_match)},
        )

    raw_amount = amount_match.group(1).strip().replace(',', '')
    try:
        # Convert float-like string (e.g. "150.00") to integer santim without floats
        if '.' in raw_amount:
            parts = raw_amount.split('.')
            birr = int(parts[0])
            santim_str = (parts[1] + '00')[:2]
            santim = int(santim_str)
            amount_minor = (birr * 100) + santim
        else:
            amount_minor = int(raw_amount) * 100
    except ValueError:
        raise SafeFetchException(
            SafeFetchErrorCode.MALFORMED_PAGE,
            f"Invalid currency amount format in page: {raw_amount}",
        )

    raw_status = status_match.group(1).strip().upper()
    if raw_status == 'SUCCESS':
        status = ProviderPaymentStatus.SUCCESS
    elif raw_status == 'PENDING':
        status = ProviderPaymentStatus.PENDING
    elif raw_status in ('FAILED', 'REVERSED'):
        status = ProviderPaymentStatus.FAILED
    else:
        status = ProviderPaymentStatus.FAILED

    payment_timestamp = date_match.group(1).strip() if date_match else "2026-11-22T00:00:00Z"

    return ProviderEvidence(
        provider=provider,
        transaction_id=txnid_match.group(1).strip(),
        amount_minor=amount_minor,
        currency="ETB",
        payment_timestamp=payment_timestamp,
        status=status,
        receiver_name=receiver_name_match.group(1).strip() if receiver_name_match else None,
        receiver_account_masked=receiver_acc_match.group(1).strip() if receiver_acc_match else None,
        payer_name_masked=payer_name_match.group(1).strip() if payer_name_match else None,
        link_host=host,
        link_path=path,
        raw_hash=raw_hash,
        http_status=http_status,
        parser_version="v0.1.0-mock",
        fetch_duration_ms=round(duration_ms, 2),
    )
